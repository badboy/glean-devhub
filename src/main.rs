use std::fs::File;
use std::io::Write;
use std::time::SystemTime;

use serde::Serialize;
use xshell::{Shell, cmd};

mod android;
mod build_metrics;
mod benchmarks;

use android::AndroidLibrarySize;
use build_metrics::{Codesize, MetricCount};
use benchmarks::Benchmark;

type Result<T, E = Box<dyn std::error::Error>> = std::result::Result<T, E>;

mod flags {
    use std::path::PathBuf;

    xflags::xflags! {
        src "./src/main.rs"

        cmd run {
            /// The revset to pick. Passed on to `revset` to determine commits to examine.
            /// If unspecified, uses `HEAD^..HEAD` (only the latest commit).
            optional -r, --revset commit: String

            /// Repository URL to clone from
            required -u, --url url: String

            /// Repository path
            required -p, --path path: PathBuf

            /// List all available metrics
            optional --list-metrics

            /// Enable only the listed metrics (comma or space-separated)
            optional -m, --metrics metrics: String
        }
    }
    // generated start
    // The following code is generated by `xflags` macro.
    // Run `env UPDATE_XFLAGS=1 cargo build` to regenerate.
    #[derive(Debug)]
    pub struct Run {
        pub revset: Option<String>,
        pub url: String,
        pub path: PathBuf,
        pub list_metrics: bool,
        pub metrics: Option<String>,
    }

    impl Run {
        #[allow(dead_code)]
        pub fn from_env_or_exit() -> Self {
            Self::from_env_or_exit_()
        }

        #[allow(dead_code)]
        pub fn from_env() -> xflags::Result<Self> {
            Self::from_env_()
        }

        #[allow(dead_code)]
        pub fn from_vec(args: Vec<std::ffi::OsString>) -> xflags::Result<Self> {
            Self::from_vec_(args)
        }
    }
    // generated end
}

fn main() -> Result<()> {
    let flags = match flags::Run::from_env() {
        Ok(flags) => flags,
        Err(err) => err.exit(),
    };

    run(flags)
}

trait MetricRecorder {
    fn record(&self, sh: &Shell) -> Result<Vec<Metric>>;

    fn name(&self) -> &'static str;
    fn description(&self) -> &'static str;
}

fn run(flags: flags::Run) -> Result<()> {
    let sh = Shell::new()?;

    let repo = flags.path;

    let metric_recorders = &[
        &AndroidLibrarySize as &dyn MetricRecorder,
        &Codesize,
        &MetricCount,
        &Benchmark,
    ];

    if flags.list_metrics {
        for recorder in metric_recorders {
            println!("{}:\t{}", recorder.name(), recorder.description());
        }

        return Ok(());
    }

    let enabled_metrics = flags.metrics.unwrap_or_else(|| String::from(""));
    let enabled_metrics = enabled_metrics.split([' ', ',']).collect::<Vec<_>>();

    if repo.is_dir() {
        sh.change_dir(&repo);
        cmd!(sh, "git fetch origin").run()?;
    } else {
        let url = flags.url;
        cmd!(sh, "git clone {url} {repo} --branch main").run()?;
        sh.change_dir(&repo);
    }

    let revset = flags.revset.unwrap_or_else(|| String::from("HEAD^..HEAD"));
    let commits = cmd!(sh, "git rev-list {revset}").read()?;
    let commits = commits.lines().rev().collect::<Vec<_>>();
    println!("Found {} commits", commits.len());

    let data_file = File::create("data.json")?;
    let commit_len = commits.len();
    for (idx, commit) in commits.iter().enumerate() {
        let wall_clock_timestamp = SystemTime::now()
            .duration_since(SystemTime::UNIX_EPOCH)
            .unwrap_or_default()
            .as_secs();

        println!("{}/{}: Checking out {commit}", idx + 1, commit_len);
        cmd!(sh, "git reset --hard {commit}").run()?;

        let timestamp = cmd!(sh, "git log --pretty=format:%ct -1 {commit}")
            .read()?
            .parse()?;

        let mut batch = MetricBatch {
            timestamp,
            metrics: vec![],
            attributes: Attributes {
                git_commit: commit.to_string(),
                wall_clock_timestamp,
            },
        };

        for recorder in metric_recorders {
            let name = recorder.name();
            if !enabled_metrics.is_empty() && !enabled_metrics.contains(&name) {
                continue;
            }

            match recorder.record(&sh) {
                Ok(metrics) => batch.metrics.extend(metrics),
                Err(e) => {
                    eprintln!(
                        "commit: {commit} - failed to run recorder {}, error: {:?}",
                        recorder.name(),
                        e
                    );
                }
            }
        }

        writeln!(&data_file, "{}", serde_json::to_string(&batch)?)?;
        data_file.sync_all()?;
    }

    Ok(())
}

#[derive(Serialize)]
struct MetricBatch {
    timestamp: u64,
    metrics: Vec<Metric>,
    attributes: Attributes,
}

#[derive(Serialize)]
struct Attributes {
    git_commit: String,
    wall_clock_timestamp: u64,
}

#[derive(Serialize)]
struct Metric {
    name: String,
    unit: String,
    value: u64,
}
